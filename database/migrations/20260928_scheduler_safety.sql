DECLARE constraint_name TEXT;
BEGIN
    FOR constraint_name IN
        SELECT conname FROM pg_constraint
        WHERE conrelid = 'public.requests'::regclass
          AND contype = 'c'
          AND (conname LIKE '%tipo_check' OR conname LIKE '%tipo_richiesta_check')
