-- La vista pubblica non rivela il codice specifico di ferie, malattia, 104 o permesso.
CREATE OR REPLACE VIEW public.roster_calendar WITH (security_barrier = true) AS
SELECT r.employee_id,
       e.nome_cognome AS employee_name,
       e.matricola,
       e.ruolo,
       r.data,
       CASE WHEN r.shift_code IN ('F', 'M', '104', 'P') THEN 'ASS'
            ELSE r.shift_code END AS shift_code
FROM public.roster AS r
JOIN public.employees AS e ON e.id = r.employee_id;

