CREATE OR REPLACE FUNCTION public.publish_roster_month(
    p_start DATE,
    p_end DATE,
    p_employee_ids UUID[],
    p_expected_roster JSONB,
    p_entries JSONB
) RETURNS INTEGER
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = pg_catalog, public
AS $$
DECLARE
    current_snapshot JSONB;
    input_count INTEGER;
    unique_input_count INTEGER;
    saved_count INTEGER;
BEGIN
    IF coalesce(auth.role(), '') <> 'service_role'
       AND coalesce(auth.jwt() -> 'app_metadata' ->> 'role', '') <> 'admin' THEN
        RAISE EXCEPTION 'Admin access required' USING ERRCODE = '42501';
    END IF;
    IF p_start IS NULL OR p_end < p_start OR p_employee_ids IS NULL
       OR cardinality(p_employee_ids) = 0 OR jsonb_typeof(p_entries) <> 'array' THEN
        RAISE EXCEPTION 'Invalid roster period or payload' USING ERRCODE = '22023';
    END IF;

    PERFORM pg_advisory_xact_lock(hashtextextended('roster:' || p_start::TEXT || ':' || p_end::TEXT, 0));

    SELECT coalesce(jsonb_agg(jsonb_build_object(
        'employee_id', r.employee_id::TEXT,
        'data', r.data::TEXT,
        'shift_code', r.shift_code,
        'is_locked', r.is_locked
    ) ORDER BY r.employee_id, r.data), '[]'::JSONB)
    INTO current_snapshot
    FROM public.roster AS r
    WHERE r.data BETWEEN p_start AND p_end
      AND r.employee_id = ANY(p_employee_ids);

    IF current_snapshot IS DISTINCT FROM coalesce(p_expected_roster, '[]'::JSONB) THEN
        RAISE EXCEPTION 'Roster changed since draft creation; reload before publishing'
            USING ERRCODE = '40001';
    END IF;

    SELECT count(*)::INTEGER,
           count(DISTINCT ((value ->> 'employee_id') || ':' || (value ->> 'data')))::INTEGER
    INTO input_count, unique_input_count
    FROM jsonb_array_elements(p_entries);

    IF input_count <> unique_input_count
       OR input_count <> cardinality(p_employee_ids) * (p_end - p_start + 1)
       OR EXISTS (
           SELECT 1 FROM jsonb_array_elements(p_entries) AS x(value)
           WHERE (value ->> 'data')::DATE NOT BETWEEN p_start AND p_end
              OR NOT ((value ->> 'employee_id')::UUID = ANY(p_employee_ids))
              OR nullif(value ->> 'shift_code', '') IS NULL
       ) THEN
        RAISE EXCEPTION 'Roster draft must contain exactly one valid shift per employee and date'
            USING ERRCODE = '22023';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM public.roster AS locked
        WHERE locked.data BETWEEN p_start AND p_end
          AND locked.employee_id = ANY(p_employee_ids)
          AND locked.is_locked
          AND NOT EXISTS (
              SELECT 1 FROM jsonb_array_elements(p_entries) AS x(value)
              WHERE (value ->> 'employee_id')::UUID = locked.employee_id
                AND (value ->> 'data')::DATE = locked.data
                AND value ->> 'shift_code' = locked.shift_code
                AND coalesce((value ->> 'is_locked')::BOOLEAN, FALSE)
          )
    ) THEN
        RAISE EXCEPTION 'Locked roster assignments cannot be changed or unlocked'
            USING ERRCODE = '42501';
    END IF;

    DELETE FROM public.roster AS r
    WHERE r.data BETWEEN p_start AND p_end
      AND r.employee_id = ANY(p_employee_ids)
      AND NOT r.is_locked;

    INSERT INTO public.roster (employee_id, data, shift_code, is_locked)
    SELECT (value ->> 'employee_id')::UUID,
           (value ->> 'data')::DATE,
           value ->> 'shift_code',
           coalesce((value ->> 'is_locked')::BOOLEAN, FALSE)
    FROM jsonb_array_elements(p_entries) AS x(value)
    ON CONFLICT (employee_id, data) DO UPDATE
        SET shift_code = EXCLUDED.shift_code,
            is_locked = EXCLUDED.is_locked;

    GET DIAGNOSTICS saved_count = ROW_COUNT;

    INSERT INTO public.audit_logs (user_id, action_type, target_resource, old_value, new_value)
    VALUES (auth.uid(), 'PUBLISH_ROSTER', p_start::TEXT || ' — ' || p_end::TEXT,
            current_snapshot::TEXT, p_entries::TEXT);

    RETURN saved_count;
END;
$$;

REVOKE ALL ON FUNCTION public.publish_roster_month(DATE, DATE, UUID[], JSONB, JSONB) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.publish_roster_month(DATE, DATE, UUID[], JSONB, JSONB) TO authenticated, service_role;
