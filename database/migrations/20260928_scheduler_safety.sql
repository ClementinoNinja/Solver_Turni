    WHEN 'FERIE' THEN 'FERIE'
    WHEN 'MALATTIA' THEN 'MALATTIA'
    WHEN '104' THEN '104'
    WHEN 'PERMESSO' THEN 'PERMESSO'
    WHEN 'MATTINA (PREF)' THEN 'MATTINA (PREF)'
    WHEN 'POMERIGGIO (PREF)' THEN 'POMERIGGIO (PREF)'
    WHEN 'NOTTE (PREF)' THEN 'NOTTE (PREF)'
    ELSE tipo_richiesta
END;

